#!/bin/bash
# docker-mailserver runs this file during container start-up, before Postfix and Dovecot start.
# LAB_ROLE selects the variant:
#   hub       - stock Dovecot capabilities; Postfix routes every lab domain to its server.
#   condstore - QRESYNC removed from the IMAP CAPABILITY response; relays through the hub.
#   uidonly   - QRESYNC and CONDSTORE removed; relays through the hub.
set -euo pipefail
role="${LAB_ROLE:-hub}"

# Plaintext IMAP, SMTP submission, and authentication: this lab only listens on 127.0.0.1.
cat > /etc/dovecot/conf.d/99-mailcal-lab.conf <<'EOF'
ssl = no
auth_allow_cleartext = yes
EOF
postconf -P 'submission/inet/smtpd_tls_security_level=none'
postconf -P 'submission/inet/smtpd_tls_auth_only=no'
postconf -e 'smtpd_tls_auth_only=no'
postconf -e 'smtpd_tls_security_level=none'
postconf -e 'smtp_tls_security_level=none'

if [[ "$role" == "hub" ]]; then
  # Deliver each lab domain to its own server. Anything else is refused: nothing leaves Docker.
  cat > /etc/postfix/transport-lab <<'EOF'
condstore.test   smtp:[condstore]:25
stalwart.test    smtp:[stalwart]:25
greenmail.test   smtp:[greenmail]:3025
james.test       smtp:[james]:25
EOF
  postconf -e 'transport_maps = texthash:/etc/postfix/transport-lab'
  postconf -e 'default_transport=error:Local Mail-Cal lab does not deliver external mail'
  postconf -e 'relay_transport=error:Local Mail-Cal lab does not relay external mail'
  # GreenMail and the host-side GreenMail account hand mail to port 25 without authentication.
  postconf -e 'smtpd_recipient_restrictions = permit_mynetworks, permit_sasl_authenticated, reject_unauth_destination'
  postconf -e 'relay_domains = dovecot.test, condstore.test, stalwart.test, greenmail.test, james.test'
else
  postconf -e 'relayhost = [dovecot]:25'
  postconf -e 'smtp_dns_support_level = disabled'
  postconf -e 'smtp_host_lookup = native'
fi

if [[ "$role" != "hub" ]]; then
  # Dovecot replaces the whole CAPABILITY list when imap_capability has no leading '+'.
  # Read the stock list from the hub server (same image) so it tracks the Dovecot version.
  default='IMAP4rev1 SASL-IR LOGIN-REFERRALS ID ENABLE IDLE SORT SORT=DISPLAY THREAD=REFERENCES THREAD=REFS THREAD=ORDEREDSUBJECT MULTIAPPEND URL-PARTIAL CATENATE UNSELECT CHILDREN NAMESPACE UIDPLUS LIST-EXTENDED I18NLEVEL=1 CONDSTORE QRESYNC ESEARCH ESORT SEARCHRES WITHIN CONTEXT=SEARCH LIST-STATUS BINARY MOVE SNIPPET=FUZZY PREVIEW=FUZZY PREVIEW STATUS=SIZE SAVEDATE LITERAL+ NOTIFY SPECIAL-USE'
  capture_capabilities() {
    local line
    exec 3<>/dev/tcp/dovecot/143 || return 1
    printf 'a LOGIN alice@dovecot.test 1\r\nb CAPABILITY\r\nc LOGOUT\r\n' >&3
    while IFS= read -r -t 10 line <&3; do
      line=${line%$'\r'}
      if [[ "$line" == "* CAPABILITY "* ]]; then echo "${line#\* CAPABILITY }"; fi
      if [[ "$line" == "* BYE"* || "$line" == "c "* || "$line" == "a NO"* ]]; then break; fi
    done
    exec 3>&- 3<&- || true
  }
  captured=''
  for attempt in $(seq 1 10); do
    captured=$(capture_capabilities 2>/dev/null | head -1 || true)
    [[ -n "$captured" ]] && break
    sleep 3
  done
  if [[ -z "$captured" ]]; then
    echo "WARNING: could not read the hub CAPABILITY list; using the built-in Dovecot 2.4 default" >&2
    captured="$default"
  fi
  # Authentication and TLS tokens are generated by imap-login and must not be listed here.
  filtered=$(echo "$captured" | tr ' ' '\n' | grep -v -E '^(AUTH=|STARTTLS$|LOGINDISABLED$|QRESYNC$)' )
  if [[ "$role" == "uidonly" ]]; then
    filtered=$(echo "$filtered" | grep -v -E '^CONDSTORE$')
  fi
  capability=$(echo "$filtered" | tr '\n' ' ' | sed 's/ *$//')
  cat >> /etc/dovecot/conf.d/99-mailcal-lab.conf <<EOF
protocol imap {
  imap_capability = $capability
}
EOF
  echo "Lab role $role: IMAP CAPABILITY set to: $capability"
fi
